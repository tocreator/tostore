import 'package:path/path.dart' as path;

import '../core/data_store_impl.dart';
import '../handler/logger.dart';
import '../model/global_config.dart';
import '../model/migration_task.dart';
import '../model/migration_write_mode.dart';
import '../model/table_context.dart';
import '../model/table_identity.dart';
import '../model/table_schema.dart';
import 'legacy_ngh/legacy_ngh_paths.dart';

/// Engine v4: isolate engine-v3 NGH directories and enqueue async leaf-nav rebuild.
///
/// Runs during engine version upgrade, before [MigrationManager.initialize].
/// Dedup reads unfinished schema tasks from disk (not in-memory pendingTasks).
/// Enqueue is persisted before the version stamp so a crash retries this class.
class V4Upgrade {
  static const int targetVersion = 4;

  final DataStoreImpl _dataStore;

  V4Upgrade(this._dataStore);

  Future<void> execute(GlobalConfig oldGlobalConfig) async {
    if (oldGlobalConfig.version >= targetVersion) {
      return;
    }

    final current = await _dataStore.getGlobalConfig() ?? oldGlobalConfig;
    if (current.version >= targetVersion) {
      return;
    }

    await _dataStore.keyManager.initialize();
    await _dataStore.tableMetaManager?.loadAllTableMetaAsync();
    await _enqueueVectorRebuilds(current);

    final after = await _dataStore.getGlobalConfig() ?? current;
    if (after.version < targetVersion) {
      await _dataStore.saveGlobalConfig(
        after.setVersion(targetVersion),
        propagateErrors: true,
      );
    }
    await _dataStore.ensureDowngradeGuardJson(version: targetVersion);

    Logger.info(
      'Database upgrade to version $targetVersion completed',
    );
  }

  Future<void> _enqueueVectorRebuilds(GlobalConfig global) async {
    final migrationManager = _dataStore.migrationManager;
    final tableMetaManager = _dataStore.tableMetaManager;
    if (migrationManager == null || tableMetaManager == null) return;

    final names = await tableMetaManager.listAllTables(onlyUserTables: true);
    final spaces = _spaces(global);

    for (final name in names) {
      final uid = await tableMetaManager.getUidByName(TableName(name));
      if (uid == null || uid.isEmpty) continue;
      final schema = await tableMetaManager.getTableSchema(uid);
      if (schema == null) continue;

      final vectorIndexes = _vectorIndexes(schema);
      if (vectorIndexes.isEmpty) continue;

      final ctx = await tableMetaManager.getTableContext(uid);
      if (ctx == null) continue;

      final hadOldWithRows = await _prepareTableSpaces(
        table: ctx,
        schema: schema,
        indexes: vectorIndexes,
        spaces: spaces,
      );
      if (!hadOldWithRows) continue;

      final wantUids = {for (final idx in vectorIndexes) idx.indexUid};
      if (await _alreadyQueuedRebuild(uid, wantUids)) continue;

      final operations = <MigrationOperation>[
        for (final idx in vectorIndexes)
          MigrationOperation(type: MigrationType.addIndex, index: idx),
      ];
      await migrationManager.addMigrationTask(
        uid,
        operations,
        startProcessing: false,
        isAutoGenerated: true,
        writeMode: MigrationWriteMode.indexOnly,
        specificIndexUids: [
          for (final idx in vectorIndexes) idx.indexUid,
        ],
        targetSchemaSnapshot: schema,
        oldSchemaSnapshot: _schemaWithoutVectorIndexes(schema),
      );
      Logger.info(
        'v4: enqueued vector index rebuild for table $name '
        '(${vectorIndexes.length} index(es), indexOnly)',
      );
    }
  }

  Future<bool> _prepareTableSpaces({
    required TableContext table,
    required TableSchema schema,
    required List<IndexSchema> indexes,
    required List<String> spaces,
  }) async {
    if (schema.isGlobal) {
      return _prepareTableIndexRoots(
        table: table,
        indexes: indexes,
        spaceName: null,
      );
    }
    var hadOldWithRows = false;
    for (final space in spaces) {
      if (await _prepareTableIndexRoots(
        table: table,
        indexes: indexes,
        spaceName: space,
      )) {
        hadOldWithRows = true;
      }
    }
    return hadOldWithRows;
  }

  Future<bool> _alreadyQueuedRebuild(
    TableUid uid,
    Set<IndexUid> wantUids,
  ) async {
    final migrationManager = _dataStore.migrationManager;
    if (migrationManager == null) return false;
    final tasks = await migrationManager.unfinishedTasksForTable(uid);
    for (final task in tasks) {
      if (task.writeMode != MigrationWriteMode.indexOnly) continue;
      final specific = task.specificIndexUids;
      if (specific == null || specific.isEmpty) continue;
      if (specific.length != wantUids.length) continue;
      var covers = true;
      for (final id in specific) {
        if (!wantUids.contains(id)) {
          covers = false;
          break;
        }
      }
      if (covers) return true;
    }
    return false;
  }

  /// Rename `ngh` → `ngh_old` when the engine-v3 nav blob is present.
  /// Returns true when that table/space had both old files and row data.
  Future<bool> _prepareTableIndexRoots({
    required TableContext table,
    required List<IndexSchema> indexes,
    required String? spaceName,
  }) async {
    final storage = _dataStore.storage;
    final tablePath = _dataStore.pathManager
        .getTablePathByContext(table, spaceName: spaceName);
    var anyOld = false;
    final hasRows = await _tableHasRows(table, spaceName);

    for (final idx in indexes) {
      final live =
          path.join(tablePath, 'index', idx.indexUid.toString(), 'ngh');
      final old = path.join(
        tablePath,
        'index',
        idx.indexUid.toString(),
        LegacyNghPaths.oldRootName,
      );
      final liveNav = path.join(live, LegacyNghPaths.navBlobName);
      final oldNav = path.join(old, LegacyNghPaths.navBlobName);

      final liveHasNav = await storage.existsFile(liveNav);
      final oldHasNav = await storage.existsFile(oldNav);

      if (liveHasNav) {
        if (await storage.existsDirectory(old)) {
          await storage.deleteDirectory(old);
        }
        await storage.moveDirectory(live, old);
        anyOld = true;
      } else if (oldHasNav) {
        anyOld = true;
      }

      if (!hasRows && anyOld) {
        if (await storage.existsDirectory(old)) {
          await storage.deleteDirectory(old);
        }
        if (await storage.existsDirectory(live)) {
          await storage.deleteDirectory(live);
        }
        anyOld = false;
      }
    }
    return anyOld && hasRows;
  }

  Future<bool> _tableHasRows(TableContext table, String? spaceName) async {
    final meta = await _dataStore.treeMetaPageService.readTableGlobalMeta(
      table,
      spaceName: spaceName,
    );
    return meta != null && meta.totalRecordCount > 0;
  }

  List<String> _spaces(GlobalConfig global) {
    return global.spaceNames.isNotEmpty
        ? global.spaceNames.toList()
        : <String>['default'];
  }

  List<IndexSchema> _vectorIndexes(TableSchema schema) {
    return [
      for (final idx in schema.getAllIndexes())
        if (idx.type == IndexType.vector && idx.indexUid.isNotEmpty) idx,
    ];
  }

  TableSchema _schemaWithoutVectorIndexes(TableSchema schema) {
    return schema.copyWith(
      indexes: [
        for (final idx in schema.indexes)
          if (idx.type != IndexType.vector) idx,
      ],
      autoIndexes: schema.autoIndexes == null
          ? null
          : [
              for (final idx in schema.autoIndexes!)
                if (idx.type != IndexType.vector) idx,
            ],
    );
  }
}
